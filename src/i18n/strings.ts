export const dictionaries: Record<Locale, Dictionary> = { en, et, lv, lt };

export function t(locale: Locale, key: StringKey, vars: Record<string, string | number> = {}): string {
  return dictionaries[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
